import React from 'react';
import { cn } from '../utils/cn';

export const Card: React.FC<React.HTMLAttributes<HTMLDivElement>> = ({
  className,
  children,
  ...props
}) => {
  return (
    <div
      className={cn(
        'rounded-xl border border-slate-200/80 bg-white text-slate-900 shadow-sm transition-all',
        className
      )}
      {...props}
    >
      {children}
    </div>
  );
};

